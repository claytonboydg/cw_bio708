## linear regression

pacman::p_load(tidyverse)


# data structure ----------------------------------------------------------

df_algae <- read_csv("data_src/data_algae.csv")
print(df_algae)

# plot conductivity (measure of eutrophication -- more ions = more conductive) vs biomass
# starting with data visualization can help you identify any anomalies early on
df_algae %>% 
  ggplot(aes(x = conductivity,
             y = biomass)) +
  geom_point()


# lm() takes a formula as the first argument
# don't forget to supply your data
m <- lm(biomass ~ conductivity,
        data = df_algae)

summary(m)


# add line from model to graph

# coef() extracts estimated coefficients
coef(m) # output is y-int and slope


# isolate the two coefficients -- coef(m)[1] is y-int, coef(m)[2] is slope
alpha <- coef(m)[1]
beta <- coef(m)[2]

# plot with line
df_algae %>% 
  ggplot(aes(x = conductivity,
             y = biomass)) +
  geom_point() +
  geom_abline(intercept = alpha,
              slope = beta, # draw the line
              colour = "blue") 


# t value is calculated as the "Estimate" divided by the "Std. Error"
# p-value then generated by calculating probability that this value occurs
# on a null distribution

# extract coefficients
theta <- coef(m)

# extract standard errors
se <- sqrt(diag(vcov(m)))

# t-value
t_value <- theta / se
print(t_value)


# unexplained variation ---------------------------------------------------

## extract residual (deviation from fitted line); 'eps' = epsilon
# this gives us 'y' (biomass) minus the predicted value given by the model
eps0 <- df_algae$biomass - (alpha + beta * df_algae$conductivity)

eps <- resid(m)

plot(eps0 ~ eps)

## visualize error
df_algae <- df_algae %>% 
  mutate(eps = eps) # add new column called eps

df_algae %>% 
  ggplot(
    aes(x = conductivity,
        y = biomass)
    ) +
  geom_point() +
  geom_abline(
    intercept = alpha,
    slope = beta
  ) +
  geom_segment(
    aes(
      x = conductivity,
      xend = conductivity,
      y = biomass,
      yend = biomass - eps
    ),
    linetype = "dashed"
  ) # this last chunk draws vertical lines (residuals) from points to fitted line


## original variation in y
y <- df_algae$biomass
ss0 <- sum((y - mean(y))^2) # null hypothesis
ss1 <- sum(eps^2) # accounting for predictor (conductivity)

ss1 / ss0 # proportion of variance that remains UNexplained

1 - (ss1 / ss0) # proportion of variance that IS explained by model (multiple R-squared)















